import { readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { generate } from "@terrarium/worlds/generator/generate";
import { runWorld } from "./src/run";
const root = join(import.meta.dir, "..");
const spec = Bun.YAML.parse(readFileSync(join(root, "worlds/town.yaml"), "utf8")) as any;
const days = Number(process.argv[2] ?? 90);
const config = generate({ ...spec, years: 1 });
rmSync(join(root, "runs/tmp-r"), { recursive: true, force: true });
const t0 = Date.now();
const s = await runWorld({ config, runId: "r", outDir: join(root, "runs/tmp-r"), until: days * 86400 });
console.log("errors", s.participantErrors, "s", Math.round((Date.now() - t0) / 1000), "wakes", s.wakes, JSON.stringify((s as any).wakesBy));
const log = readFileSync(s.logPath, "utf8").trim().split("\n").map((l) => JSON.parse(l));
const ev = log.filter((e) => e.kind === "event").map((e) => ({ t: e.t, ...e.body }));
const units = (task: string) => ev.filter((e) => e.event === "worked" && e.task === task).reduce((a, e) => a + e.units, 0);
console.log("made", units("make"), "served", units("serve"), "collected", units("collect"), "taught", units("teach"), "treated", units("treat"));
const recs = ev.filter((e) => e.event === "recorded").map((e) => e.record);
console.log("died", ev.filter((e) => e.event === "person_died").length, "registered", recs.filter((r) => r.kind === "death_registration").length, "refunds", recs.filter((r) => r.kind === "delivery_note" && r.data?.refund > 0).length, "complaints", recs.filter((r) => r.kind === "complaint").length);
const refused: Record<string, number> = {};
for (const e of ev.filter((e) => e.event === "action_refused")) refused[e.code] = (refused[e.code] ?? 0) + 1;
console.log("refused", JSON.stringify(refused));
